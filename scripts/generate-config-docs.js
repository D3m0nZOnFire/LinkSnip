#!/usr/bin/env node
/**
 * Generates docs/CONFIGURATION.md from config/schema.js and config/roles.default.json,
 * so the reference can't drift from what the app validates.
 *
 *   npm run docs:config
 *
 * A test fails when the committed file is out of date.
 */
const fs = require('fs');
const path = require('path');
const schema = require('../config/schema');
const defaultRoles = require('../config/roles.default.json');

const OUTPUT = path.join(__dirname, '..', 'docs', 'CONFIGURATION.md');

const ENV_VARS = [
  ['SESSION_SECRET', 'required', 'Signs login sessions. Generate with `openssl rand -hex 32`. The app refuses to start without it.'],
  ['IP_HASH_SECRET', 'required', 'Key for the stored hashes of visitor IPs (analytics, reports), so a copy of the database can\'t be turned back into IPs. At least 32 characters, different from `SESSION_SECRET`. Generate with `openssl rand -hex 32`, and keep it: a new one restarts unique-visitor counts.'],
  ['DATA_DIR', 'project folder (`/data` in Docker)', 'Holds `database.db`, `uploads/`, `backups/`, `settings.json` and `roles.json`.'],
  ['PORT', '`8081`', 'Port the app listens on.'],
  ['NODE_ENV', '`development` (`production` in Docker)', '`development` logs every SQL query.'],
  ['TRUST_PROXY', '`1`', 'Reverse proxies in front of the app: a hop count, `true`/`false`, or an address list (Express `trust proxy`). Use `0` if nothing is in front.'],
  ['DOMAIN', '`localhost`', 'Only for the bundled Caddy (`docker compose --profile caddy up -d`): the domain to get a certificate for.']
];

const code = (v) => `\`${JSON.stringify(v)}\``;
const escape = (text) => String(text).replace(/\|/g, '\\|');
const limitCell = (v) => (v === null ? 'unlimited' : v === 0 ? 'none' : String(v));

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `|${headers.map(() => '---').join('|')}|`,
    ...rows.map(r => `| ${r.join(' | ')} |`)
  ].join('\n');
}

function renderConfigurationDoc() {
  const roleNames = Object.keys(defaultRoles.roles);
  const roleHeaders = roleNames.map(r => `\`${r}\``);

  return `<!-- Generated by scripts/generate-config-docs.js from config/schema.js. Do not edit by hand: run \`npm run docs:config\`. -->

# Configuration

LinkSnip is configured in three places:

- **Environment variables**: infrastructure only (secrets, paths, ports).
- **\`DATA_DIR/settings.json\`**: how the instance behaves. Edit it in **Admin → Settings** or by hand.
- **\`DATA_DIR/roles.json\`**: who may do what, and how much. Edit it by hand; Admin → Settings shows it read-only.

Both JSON files are created with every key and its default on first start, so opening them shows every option.
Missing keys use the defaults, so a partial file is fine.

**Changes apply without a restart.** The files are checked every 2 seconds, which also works on Docker bind mounts.
Every value is validated. An invalid file is logged, naming the file, key and problem
(for example \`roles.json: roles.trusted.limits.maxFileSizeMB must be a number or null (got "100MB")\`),
and the last good configuration stays in use.

## Environment variables

${table(['Variable', 'Default', 'Description'], ENV_VARS.map(([name, def, desc]) => [`\`${name}\``, def, desc]))}

## settings.json

${table(['Key', 'Default', 'Description'], Object.entries(schema.SETTINGS).map(([key, spec]) => [
    `\`${key}\``,
    code(spec.default),
    escape(spec.description) + (spec.env ? ` Seeded once from \`${spec.env}\` if set when the file is first created.` : '')
  ]))}

Switching off a \`features.*\` key removes that feature for everyone, admins included: its pages and API
return 404 and its buttons and menus are hidden.

**Country lookup:** \`geo.enabled\` looks countries up in a local DB-IP Lite database, \`DATA_DIR/geo/dbip-country-lite.mmdb\`
(CC BY 4.0; analytics pages credit DB-IP). Visitor IPs never leave the server. LinkSnip downloads the file on start
and checks daily for the monthly update; the only thing sent to db-ip.com is the month. Without outbound access,
download \`dbip-country-lite-YYYY-MM.mmdb.gz\` from https://db-ip.com/db/download/ip-to-country-lite yourself, unpack
it to that path, and it's picked up within a minute. Without the file, countries are recorded as Unknown.

## roles.json

A role is a named set of permissions and limits. Every account has one; visitors without an account use
\`anonymous\`. Admins (a separate flag, not a role) have every permission and no limits.

- **\`defaultRole\`** (default \`"${defaultRoles.defaultRole}"\`): the role of accounts without one, including new
  registrations. An account with an unknown role also gets it.
- **Built-in roles:** ${roleNames.map(r => `\`${r}\``).join(', ')}. Anything you set is merged over their defaults.
- **Custom roles:** add a new name under \`roles\`. It starts as a copy of \`user\`, with your changes on top.
- **Limits:** a whole number, or \`null\` for unlimited. \`0\` means none allowed.
- \`files.globalMaxFileSizeMB\` in settings.json caps \`maxFileSizeMB\` for every role whose limit isn't \`null\`.

### Permissions

${table(['Permission', 'Description', ...roleHeaders], Object.entries(schema.PERMISSIONS).map(([name, description]) => [
    `\`${name}\``,
    escape(description),
    ...roleNames.map(r => (defaultRoles.roles[r].permissions[name] ? '✓' : '✗'))
  ]))}

### Limits

${table(['Limit', 'Description', ...roleHeaders], Object.entries(schema.LIMITS).map(([name, description]) => [
    `\`${name}\``,
    escape(description),
    ...roleNames.map(r => limitCell(defaultRoles.roles[r].limits[name]))
  ]))}

### Example: an internal-only instance

Only people with an account can create anything, and only admins can create accounts:

\`\`\`json
// roles.json
{
  "roles": {
    "anonymous": {
      "permissions": { "createUrls": false, "createPastes": false, "createBundles": false }
    }
  }
}
\`\`\`

\`\`\`json
// settings.json (the rest of the file stays as it is)
{
  "registration": { "open": false }
}
\`\`\`
`;
}

if (require.main === module) {
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, renderConfigurationDoc());
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
}

module.exports = { renderConfigurationDoc };
